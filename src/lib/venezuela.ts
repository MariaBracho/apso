/** Las ciudades de un estado. Vacío si el nombre no es de ninguno. */
export function ciudadesDe(estado: string): string[] {
  return ESTADOS.find((e) => e.nombre === estado)?.ciudades ?? [];
}

/**
 * Si esa ciudad es de ese estado.
 *
 * Lo comprueba el servidor antes de guardar: los dos campos llegan del
 * navegador y un destino inventado manda la encomienda a ninguna parte.
 */
export function esDestinoValido(estado: string, ciudad: string): boolean {
  return ciudadesDe(estado).includes(ciudad);
}
