/**
 * La división político-territorial de Venezuela, para el destino de un envío.
 *
 * Va dentro del repo y no detrás de una API. Un checkout que depende de un
 * servicio ajeno deja de vender el día que ese servicio se cae, y esto son
 * 24 estados y 480 ciudades que cambian una vez cada década: no hay nada
 * que ir a consultar.
 *
 * Estado y ciudad, sin municipio en medio: es lo que pide una encomienda para
 * cotizar el flete. Y una ciudad no cuelga de un municipio —Caracas misma está
 * repartida entre varios—, así que encadenarlos sería inventarse un vínculo
 * que no existe.
 *
 * Sale de github.com/zokeber/venezuela-json, con dos correcciones: Vargas pasó
 * a llamarse La Guaira en 2019 y allí sigue con el nombre viejo, y Distrito
 * Capital venía sin ciudades.
 *
 * Los nombres se dejan tal cual vienen, con su desambiguación incluida
 * («Píritu Falcón», «Chaguaramas Guárico»): quitarla a mano se llevaría por
 * delante los que la tienen de verdad, como Ciudad Bolívar.
 */

